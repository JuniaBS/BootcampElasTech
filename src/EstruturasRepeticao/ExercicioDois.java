/*
2 - Mostre a contagem regressiva de 10 até 1 e depois a palavra "Fim!".
 */
package EstruturasRepeticao;

public class ExercicioDois {
    public static void main(String[] args) {
        for(int i = 10; i >= 0 ; i -- ) {
            System.out.println(i);
        }

        System.out.println("Fim!");
    }
}
